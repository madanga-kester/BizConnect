export const formatKes = (amount: number) => new Intl.NumberFormat("en-KE", { style: "currency", currency: "KES", maximumFractionDigits: 0 }).format(amount).replace("KES", "KSh");
export const formatDate = (date: string | Date, language: "en" | "sw" = "en") => new Intl.DateTimeFormat(language === "sw" ? "sw-KE" : "en-KE", { day: "numeric", month: "short", year: "numeric" }).format(new Date(date));
export function formatKenyanPhone(phone: string): string {
  const digits = phone.replace(/\D/g, "");
  if (digits.startsWith("254") && digits.length === 12) return `+254 ${digits.slice(3, 6)} ${digits.slice(6, 9)} ${digits.slice(9)}`;
  if (digits.startsWith("0") && digits.length === 10) return `+254 ${digits.slice(1, 4)} ${digits.slice(4, 7)} ${digits.slice(7)}`;
  return phone.trim();
}
export const isValidKenyanPhone = (phone: string) => /^(?:\+?254|0)(?:1\d|7\d)\d{7}$/.test(phone.replace(/[\s-]/g, ""));